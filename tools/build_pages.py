PAPER_RE = re.compile(r"\{id:'([^']+)',name:'([^']+)',date:'([^']+)',shift:'([^']*)',head:'[^']*',sub:'[^']*',pat:'([^']+)',path:'([^']+)',min:(\d+)\}")
