def js_lists(block):
    """'KEY':['a','b'] or KEY:['a',"b's"] pairs from a JS object literal."""
    out = {}
    for key, body in re.findall(r"'?([\w| ]+)'?\s*:\s*\[(.*?)\]", block, re.S):
        out[key.strip()] = [a or b for a, b in re.findall(r"'([^']*)'|\"([^\"]*)\"", body)]
    return out
