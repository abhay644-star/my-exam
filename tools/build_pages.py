def paper_label(p):
    """'JEE Main 2026, 2 April, Shift 1', 'JEE Advanced 2026, Paper 1', 'NEET (UG) 2026, 21 June (re-exam), Code 50'."""
    year = re.search(r'\d{4}', p['name']).group(0)
    parts = [re.sub(r'\s+', ' ', p['date'].replace(year, '')).strip(), p['shift']]
    return p['name'] + ''.join(', ' + x for x in parts if x)

def paper_path(e, p):
    return f"/{e['list']}/{slug(paper_label(p)[len(e['crumb']):])}/"

# the same rules as examQs in index.html: a "less than" sign is not a tag; a one-line $$…$$ formula becomes a wrapping one
safe = lambda s: re.sub(r'<(?!/?(br|table|tr|td|th)\b)', '&lt;', '' if s is None else str(s))
wrap_math = lambda s: re.sub(r'\$\$([\s\S]+?)\$\$', lambda m: m.group(0) if re.search(r'\\begin\{', m.group(1)) else f'<div class="dm">$\\displaystyle {m.group(1)}$</div>', s)
num = lambda x: str(int(x)) if float(x) == int(x) else str(x)

def answer(q, OL):
    """(text shown, key for the tests: option numbers, a number or range, or 'dropped')."""
    a = q['answer']
    if q.get('dropped'):
        return 'Dropped: full marks to everyone', 'dropped'
    if q['type'] == 'num':
        lo, hi = (a['lo'], a['hi']) if isinstance(a, dict) else (a, a)
        rng = lambda l, h: num(l) if l == h else f'{num(l)} to {num(h)}'
        # further ranges the final key accepts are shown too; the test key is the main range
        text = ' or '.join([rng(lo, hi)] + [rng(r['lo'], r['hi']) for r in (q.get('accept') or [])])
        return text, (num(lo) if lo == hi else f'{num(lo)}~{num(hi)}')
    if q['type'] == 'multi':
        text = ', '.join(f'({OL[j]})' for j in a)
        if q.get('alts'):
            text += '; the final key also accepts ' + ' or '.join(', '.join(f'({OL[j]})' for j in s) for s in q['alts'])
        return text, ','.join(map(str, a))
    if q.get('accept'):
        return ' or '.join(f'({OL[j]})' for j in q['accept']) + ' (either is accepted)', '/'.join(map(str, q['accept']))
    return f'({OL[a]})', str(a)

def solved(q, no, OL, fig):
    """One question with its options, answer and worked solution (answer hidden until opened)."""
    text = wrap_math(safe(q['text'])) + (f'<img class="qfig" src="{fig}{q["fig"]}" alt="Figure for question {no}" loading="lazy">' if q.get('fig') else '')
    opts = ''
    if q['type'] != 'num':
        opts = '<ol type="{}">{}</ol>'.format('1' if OL == '1234' else 'a', ''.join(
            f'<li><img class="ofig" src="{fig}{q["optionFigs"][j]}" alt="Option {OL[j]}" loading="lazy"></li>' if q.get('optionFigs') and q['optionFigs'][j] else f'<li>{wrap_math(safe(o))}</li>'
            for j, o in enumerate(q['options'])))
    sol = f'<p>{wrap_math(safe(q["sol"]))}</p>' if q.get('sol') else ''
    return (f'<li class="sq"><p class="sqt"><small>Question {no} · {esc(q["subject"])} · {esc(q["chapter"])}</small><br>{text}</p>{opts}'
            f'<details><summary>Show answer and solution</summary><p><b>Answer:</b> {wrap_math(safe(answer(q, OL)[0]))}</p>{sol}</details></li>')

def dur_text(m):
    h, r = divmod(int(m), 60)
    return f'{h} hours' + (f' {r} minutes' if r else '')

