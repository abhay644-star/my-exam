def bank_count(subj, cls, ch):
    return sum(1 for q in banks.get(subj, []) if q['c'] == cls and q['t'] == ch)
def has_chapter_page(subj, cls, ch):
    if subj not in CH_SCOPE.get(cls, []):
        return False
